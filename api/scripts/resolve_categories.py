#!/usr/bin/env python3
"""Resolves api/seeds/<id>.txt against the iTunes Search API and writes api/src/categories.mjs.

Stdlib only. Throttled to about 18 requests a minute (3.2 s apart, 60 s pause on 403/429).
The match rules are those of scripts/seed-songs.mjs: covers, karaoke, remixes and live
versions are rejected.

Usage:
  python3 -I api/scripts/resolve_categories.py [--only ID ...] [--refresh]
By default seeds that are already resolved are kept, so a stopped run resumes.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
import unicodedata
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

API = Path(__file__).resolve().parent.parent
SEEDS = API / "seeds"
OUT = API / "src" / "categories.mjs"
COUNTRIES = ("AT", "DE", "US")
DELAY = 3.2
HEADER = "// Generated by api/scripts/resolve_categories.py from api/seeds/; do not edit.\n"

BAD_WORDS = [
    "karaoke", "tribute", "cover version", "as made famous", "originally performed",
    "in the style of", "8-bit", "lullaby", "instrumental", r"\bacoustic\b", r"\blive at\b", r"\bdemo\b",
]
VARIANT_WORDS = {"acoustic", "demo", "version", "edit", "radio", "live", "remix", "mix", "instrumental"}
CREDIT = re.compile(r"^(feat|featuring|with|from)\b")


def bad_regex(allow_instrumental: bool = False) -> re.Pattern:
    words = [w for w in BAD_WORDS if not (allow_instrumental and w == "instrumental")]
    return re.compile("|".join(words), re.I)


def norm(s: str) -> str:
    s = unicodedata.normalize("NFD", s.lower())
    s = re.sub(r"[̀-ͯ]", "", s)
    s = re.sub(r"[^a-z0-9 ]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def tokens(s: str) -> list[str]:
    return [t for t in s.split(" ") if t and t != "the"]


def same_artist(ra: str, na: str) -> bool:
    if ra == na:
        return True
    have = set(tokens(ra))
    return all(t in have for t in tokens(na))


def alternate_version(track_name: str, nt: str) -> bool:
    seed_words = set(tokens(nt))
    if any(w in VARIANT_WORDS and w not in seed_words for w in tokens(norm(track_name))):
        return True
    qualifiers = [norm(m) for m in re.findall(r"[(\[]([^)\]]*)[)\]]", track_name)]
    return any(q and q not in nt and not CREDIT.match(q) for q in qualifiers)


def pick_match(results: list[dict], artist: str, title: str, bad: re.Pattern | None = None):
    bad = bad or bad_regex()
    na, nt = norm(artist), norm(title)
    scored = []
    for r in results:
        if not (r.get("previewUrl") and r.get("trackName") and r.get("artistName")):
            continue
        if bad.search(f"{r['artistName']} {r['trackName']} {r.get('collectionName') or ''}"):
            continue
        ra, rt = norm(r["artistName"]), norm(r["trackName"])
        if not same_artist(ra, na):
            continue
        score = 0
        if rt == nt:
            score += 4
        elif rt.startswith(nt) or nt.startswith(rt):
            score += 2
        elif nt in rt or rt in nt:
            score += 1
        if score == 0:
            continue
        score += 3 if ra == na else 1
        if alternate_version(r["trackName"], nt):
            score -= 3
        scored.append((score, len(scored), r))
    scored.sort(key=lambda x: (-x[0], x[1]))
    return scored[0][2] if scored and scored[0][0] >= 3 else None


def parse_seeds(text: str) -> tuple[bool, list[tuple[str, str]]]:
    """Returns (allow_instrumental, [(artist, title)]). One 'Artist - Title' per line."""
    lines = text.splitlines()
    allow = bool(lines) and lines[0].strip().lower() == "# allow: instrumental"
    seeds = []
    for line in lines:
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        artist, sep, title = line.partition(" - ")
        if not sep or not artist.strip() or not title.strip():
            raise ValueError(f"not 'Artist - Title': {line!r}")
        seeds.append((artist.strip(), title.strip()))
    return allow, seeds


def seed_key(artist: str, title: str) -> str:
    return norm(f"{artist} - {title}")


def read_existing() -> dict[str, list]:
    if not OUT.exists():
        return {}
    text = OUT.read_text(encoding="utf-8")
    start = text.index("{")
    end = text.rindex("}")
    return json.loads(text[start:end + 1])


def write_out(data: dict[str, list]) -> None:
    parts = []
    for cid in sorted(data):
        rows = ",\n".join("    " + json.dumps(e, ensure_ascii=False) for e in data[cid])
        parts.append(f"  {json.dumps(cid)}: [\n{rows}\n  ]")
    body = ",\n".join(parts)
    OUT.write_text(f"{HEADER}export const CATEGORY_TRACKS = {{\n{body}\n}};\n", encoding="utf-8")


def search(artist: str, title: str, country: str):
    q = urllib.parse.urlencode({"term": f"{artist} {title}", "media": "music", "entity": "song",
                                "limit": 8, "country": country})
    req = urllib.request.Request(f"https://itunes.apple.com/search?{q}",
                                 headers={"User-Agent": "FiveGuesses-seed/1.0"})
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=20) as r:
                return json.loads(r.read().decode("utf-8")).get("results", [])
        except urllib.error.HTTPError as e:
            if e.code in (403, 429):
                print(f"  throttled ({e.code}), waiting 60 s", flush=True)
                time.sleep(60)
                continue
            print(f"  HTTP {e.code}, retry {attempt + 1}/3", flush=True)
        except (urllib.error.URLError, TimeoutError, ValueError) as e:
            print(f"  error ({e}), retry {attempt + 1}/3", flush=True)
        time.sleep(5)
    return None


def resolve(artist: str, title: str, bad: re.Pattern):
    for country in COUNTRIES:
        results = search(artist, title, country)
        time.sleep(DELAY)
        if results is None:
            continue
        m = pick_match(results, artist, title, bad)
        if m:
            return [m["trackId"], country, artist, title]
    return None


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--only", action="append", default=[], help="category id (repeatable)")
    ap.add_argument("--refresh", action="store_true", help="resolve every seed again")
    args = ap.parse_args(argv)
    ids = args.only or sorted(p.stem for p in SEEDS.glob("*.txt"))
    data = read_existing()
    for cid in ids:
        path = SEEDS / f"{cid}.txt"
        if not path.exists():
            print(f"no seed file {path}", file=sys.stderr)
            return 2
        allow, seeds = parse_seeds(path.read_text(encoding="utf-8"))
        bad = bad_regex(allow)
        known = {} if args.refresh else {seed_key(e[2], e[3]): e for e in data.get(cid, [])}
        rows, misses = [], []
        for i, (artist, title) in enumerate(seeds, 1):
            key = seed_key(artist, title)
            if key in known:
                rows.append(known[key])
                continue
            print(f"[{cid} {i}/{len(seeds)}] {artist} - {title} ... ", end="", flush=True)
            row = resolve(artist, title, bad)
            print("OK" if row else "MISS", flush=True)
            if row:
                rows.append(row)
            else:
                misses.append(f"{artist} - {title}")
        seen, unique = set(), []
        for r in rows:
            if r[0] not in seen:
                seen.add(r[0])
                unique.append(r)
        data[cid] = unique
        write_out(data)
        print(f"{cid}: {len(unique)}/{len(seeds)} resolved", flush=True)
        for m in misses:
            print(f"  miss: {m}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
